package com;

public class Kalkulator {
    public static void main(String[] args) {
        int a = 1;
        int b = 2;

        System.out.println("a = " + a);
        System.out.println("b = " + b);

        int c = a + b;

        System.out.println("a + b = " + c);

        c = a * b;

        System.out.println("a * b = " + c);
    }
}
